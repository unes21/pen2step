"""Write Table 3 / Table 4 style markdown for one or more backends from their stats.json files.

Every number is read from results/replay[_<backend>][_equipment]/stats.json (src/stats.py) and the
matching trivial.json; nothing is typed by hand. Backends without a stats.json are listed as
missing rather than skipped silently.

Usage:
    python tools/make_paper_tables.py --backends open,anthropic,openai --out results/PAPER_TABLES_frontier.md
    python tools/make_paper_tables.py --backends open,anthropic,openai --split equipment \
        --out results/PAPER_TABLES_equipment.md
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
T3 = [("Bare model (N = 1)", "raw_mv_bare"), ("Runtime guards only (N = 1)", "raw_mv"),
      ("Full shell (N = 1)", "multiview_n1"), ("Full shell (N = 3)", "multiview_n3"),
      ("+ OCR dims, naive (N = 3)", "full_ocr_naive"), ("+ OCR dims, floor (N = 3)", "full_ocr"),
      ("+ GT dims, oracle (N = 3)", "full_gt")]
T4 = [("Bare model", "raw_mv_bare"), ("+ partial-execution salvage only", "bare_plus_partial"),
      ("+ scale recovery only", "bare_plus_scale"), ("+ AST repair", "bare_plus_repair"),
      ("+ AST repair and scale recovery", "bare_plus_repair_scale"), ("Full shell", "multiview_n1"),
      ("− AST repair", "n1_minus_repair"), ("− partial-execution salvage", "n1_minus_partial"),
      ("− result discovery", "n1_minus_discover"), ("− base-plate removal", "n1_minus_base"),
      ("− arc fallback", "n1_minus_arc"), ("− scale recovery", "n1_minus_scale")]


def base(backend, split):
    b = "" if backend in (None, "", "open") else f"_{backend}"
    return ROOT / f"results/replay{b}{'_equipment' if split == 'equipment' else ''}"


def f3(x):
    return "n/a" if x is None else f"{x:.3f}"


def table3(S, label):
    C, R = S["orig"]["conditions"], S["rescaled"]["conditions"]
    n = S["n_parts"]
    out = [f"### {label}: replayed conditions (n = {n}, seeds {S['seeds']})", "",
           "| Condition | Valid solids | F raw | F aligned [95% CI] | F aligned, scale-norm. | F aligned, rescaled GT | "
           "Chamfer al. (mm) | DimE | VolE |", "|---|---|---|---|---|---|---|---|---|"]
    for lab, c in T3:
        if c not in C:
            continue
        o = C[c]
        ci = f"{f3(o['F_al_all'])} [{f3(o['F_al_all_ci'][0])}, {f3(o['F_al_all_ci'][1])}]"
        cd = "n/a" if o["CD_al_valid"] is None else f"{o['CD_al_valid']:.1f}"
        out.append(f"| {lab} | {round(o['SVR_mean'] * n)}/{n} | {f3(o['F_raw_all'])} | {ci} | {f3(o['F_al_sn_all'])} | "
                   f"{f3(R[c]['F_al_all'])} | {cd} | {f3(o['DimE_valid'])} | {f3(o['VolE_valid'])} |")
    out.append("")
    return out


def table4(S, label):
    C, n = S["orig"]["conditions"], S["n_parts"]
    out = [f"### {label}: mechanism ablation (candidate 0, N = 1, no dimensions)", "",
           "| Configuration | Valid solids | F aligned | F aligned, scale-norm. |", "|---|---|---|---|"]
    for lab, c in T4:
        if c in C:
            o = C[c]
            out.append(f"| {lab} | {round(o['SVR_mean'] * n)}/{n} | {f3(o['F_al_all'])} | {f3(o['F_al_sn_all'])} |")
    out.append("")
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--backends", default="open")
    ap.add_argument("--split", default="real", choices=["real", "equipment"])
    ap.add_argument("--out", required=True)
    a = ap.parse_args()
    names = [b.strip() for b in a.backends.split(",") if b.strip()]
    loaded, missing = {}, []
    for b in names:
        p = base(b, a.split) / "stats.json"
        if p.exists():
            loaded[b] = json.loads(p.read_text(encoding="utf-8"))
        else:
            missing.append(f"{b} ({p.relative_to(ROOT).as_posix()})")
    tv = base(None, a.split) / "trivial.json"
    triv = json.loads(tv.read_text(encoding="utf-8")) if tv.exists() else None

    L = [f"# Replayed results by backend ({a.split} split)", "",
         "Generated by `tools/make_paper_tables.py` from `stats.json` files written by `src/stats.py`; "
         "same statistical convention for every backend (all parts, invalid F = 0, per-part seed means, "
         "10,000-resample bootstrap CIs). Decoding settings per backend are in `results/replay/provenance.json`.", ""]
    if missing:
        L += ["Not yet available: " + ", ".join(missing), ""]
    if loaded:
        L += ["## Side by side", "", "| Backend | Bare | Guards only | Full shell N = 1 | Full shell N = 3 | "
              "F aligned, full shell N = 3 [95% CI] | F aligned, + GT dims [95% CI] | Constant box |",
              "|---|---|---|---|---|---|---|---|"]
        for b, S in loaded.items():
            C, n = S["orig"]["conditions"], S["n_parts"]
            v = lambda c: f"{round(C[c]['SVR_mean'] * n)}/{n}" if c in C else "n/a"
            fc = lambda c: (f"{f3(C[c]['F_al_all'])} [{f3(C[c]['F_al_all_ci'][0])}, {f3(C[c]['F_al_all_ci'][1])}]"
                            if c in C else "n/a")
            box = f3(triv["orig"]["constant_box"]["F_al"]) if triv else "n/a"
            L.append(f"| {b} | {v('raw_mv_bare')} | {v('raw_mv')} | {v('multiview_n1')} | {v('multiview_n3')} | "
                     f"{fc('multiview_n3')} | {fc('full_gt')} | {box} |")
        L.append("")
        for b, S in loaded.items():
            L += table3(S, b) + table4(S, b)
    Path(a.out).write_text("\n".join(L), encoding="utf-8")
    print(a.out, "| loaded:", list(loaded), "| missing:", missing)


if __name__ == "__main__":
    main()
